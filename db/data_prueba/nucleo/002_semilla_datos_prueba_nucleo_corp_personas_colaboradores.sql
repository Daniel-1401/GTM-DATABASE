IF NOT EXISTS
(
    SELECT 1
    FROM [catalogo].[TipoDocumento]
    WHERE [IdTipoDocumento] = @IdTipoDocumento
      AND [CodigoTipoDocumento] = N'DNI'
)
    THROW 51000, N'No se encontró el tipo de documento DNI con IdTipoDocumento = 1.', 1;

IF NOT EXISTS
(
    SELECT 1
    FROM [catalogo].[EstadoCivil]
    WHERE [IdEstadoCivil] = @IdEstadoCivil
      AND [CodigoEstadoCivil] = N'SOLTERO'
)
    THROW 51001, N'No se encontró el estado civil SOLTERO con IdEstadoCivil = 1.', 1;

