(
    SELECT 1
    FROM [catalogo].[Genero]
    WHERE [IdGenero] = @IdGenero
      AND [NombreGenero] = N'Masculino'
)
    THROW 51002, N'No se encontró el género Masculino con IdGenero = 2.', 1;

