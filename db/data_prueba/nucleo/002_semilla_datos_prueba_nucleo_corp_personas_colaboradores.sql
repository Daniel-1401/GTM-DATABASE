DECLARE @PersonasInsertadas TABLE
(
    [IdPersona] BIGINT NOT NULL,
    [IdPersonaCorporativa] UNIQUEIDENTIFIER NOT NULL PRIMARY KEY
);

BEGIN TRY
    BEGIN TRANSACTION;

    INSERT INTO [rrhh].[Persona]
    (
        [IdPersonaCorporativa],
        [Nombres],
        [ApellidoPaterno],
        [ApellidoMaterno],
        [FechaNacimiento],
        [IdEstadoCivil],
        [IdGenero],
        [IdPaisNacionalidad]
    )
    OUTPUT
        INSERTED.[IdPersona],
        INSERTED.[IdPersonaCorporativa]
    INTO @PersonasInsertadas ([IdPersona], [IdPersonaCorporativa])
    SELECT
        [IdPersonaCorporativa],
        [Nombres],
        [ApellidoPaterno],
        [ApellidoMaterno],
        CONVERT(DATE, '2000-01-01'),
        @IdEstadoCivil,
        @IdGenero,
        @IdPais
    FROM @Carga;

    INSERT INTO [rrhh].[DocumentoPersona]
    (
        [IdPersona],
        [IdTipoDocumento],
        [NumeroDocumento],
        [IdPaisEmision],
        [EsPrincipal],
        [FechaInicioVigencia],
        [FechaFinVigencia]
    )
    SELECT
        [persona].[IdPersona],
        @IdTipoDocumento,
        [carga].[NumeroDocumento],
        @IdPais,
        CONVERT(BIT, 1),
        CONVERT(DATE, '2026-01-01'),
        CONVERT(DATE, '2099-01-01')
    FROM @Carga AS [carga]
    INNER JOIN @PersonasInsertadas AS [persona]
        ON [persona].[IdPersonaCorporativa] = [carga].[IdPersonaCorporativa];

    INSERT INTO [rrhh].[Colaborador]
    (
        [IdColaboradorCorporativo],
        [IdPersona]
    )
    SELECT
        NEWID(),
        [IdPersona]
    FROM @PersonasInsertadas;

    COMMIT TRANSACTION;
END TRY
BEGIN CATCH
    IF XACT_STATE() <> 0 ROLLBACK TRANSACTION;
    THROW;
END CATCH;
