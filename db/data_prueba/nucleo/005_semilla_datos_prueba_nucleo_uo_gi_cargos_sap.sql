IF EXISTS
(
    SELECT 1
    FROM @PosicionesSAP AS [posicionSAP]
    LEFT JOIN [organizacion].[Cargo] AS [cargo]
        ON [cargo].[IdEmpresaReferencia] = @IdEmpresaReferencia
       AND [cargo].[CodigoCargo] =
           N'GI-CARGO-' + CONVERT(NVARCHAR(20), [posicionSAP].[IdPosicionFuente])
    WHERE [cargo].[IdCargo] IS NULL
)
    THROW 51001, N'El archivo de posiciones SAP contiene cargos GI no cargados.', 1;

BEGIN TRY
    BEGIN TRANSACTION;

    INSERT INTO [organizacion].[CargoSAP]
    (
        [IdEmpresaReferencia],
        [IdCargo],
        [CodigoCargoSAP]
    )
    SELECT
        @IdEmpresaReferencia,
        [cargo].[IdCargo],
        [posicionSAP].[CodigoCargoSAP]
    FROM @PosicionesSAP AS [posicionSAP]
    INNER JOIN [organizacion].[Cargo] AS [cargo]
        ON [cargo].[IdEmpresaReferencia] = @IdEmpresaReferencia
       AND [cargo].[CodigoCargo] =
           N'GI-CARGO-' + CONVERT(NVARCHAR(20), [posicionSAP].[IdPosicionFuente])
    WHERE NOT EXISTS
    (
        SELECT 1
        FROM [organizacion].[CargoSAP] AS [existente]
        WHERE [existente].[IdEmpresaReferencia] = @IdEmpresaReferencia
          AND [existente].[CodigoCargoSAP] = [posicionSAP].[CodigoCargoSAP]
    );

    COMMIT TRANSACTION;
END TRY
BEGIN CATCH
    IF XACT_STATE() <> 0 ROLLBACK TRANSACTION;
    THROW;
END CATCH;
