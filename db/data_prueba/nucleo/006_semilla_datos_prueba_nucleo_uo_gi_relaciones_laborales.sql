DECLARE @ColaboradoresCO TABLE
(
    [NumeroDocumento] NVARCHAR(50) NOT NULL PRIMARY KEY,
    [IdColaboradorCorporativo] UNIQUEIDENTIFIER NOT NULL
);

INSERT INTO @ColaboradoresCO
(
    [NumeroDocumento],
    [IdColaboradorCorporativo]
)
SELECT
    [documento].[NumeroDocumento],
    [colaborador].[IdColaboradorCorporativo]
FROM [GSBEDEV01\CO].[PERSONALMANEGEMENTCORP].[rrhh].[DocumentoPersona] AS [documento]
INNER JOIN [GSBEDEV01\CO].[PERSONALMANEGEMENTCORP].[rrhh].[Colaborador] AS [colaborador]
    ON [colaborador].[IdPersona] = [documento].[IdPersona]
WHERE [documento].[IdTipoDocumento] = 1
  AND [documento].[IdPaisEmision] = 1
  AND [documento].[EsPrincipal] = 1;

IF EXISTS
(
    SELECT 1
    FROM @Carga
    WHERE TRY_CONVERT(DATE, [FechaIngresoTexto], 103) IS NULL
)
    THROW 51001, N'El archivo de colaboradores contiene una fecha de ingreso inválida.', 1;

IF EXISTS
(
    SELECT 1
    FROM @Carga AS [carga]
    LEFT JOIN @ColaboradoresCO AS [colaboradorCO]
        ON [colaboradorCO].[NumeroDocumento] = [carga].[NumeroDocumento]
    WHERE [colaboradorCO].[IdColaboradorCorporativo] IS NULL
)
    THROW 51002, N'No se encontró el colaborador corporativo en la instancia CO para uno de los documentos.', 1;

IF EXISTS
(
    SELECT 1
    FROM @Carga AS [carga]
    LEFT JOIN [organizacion].[CargoSAP] AS [cargoSAP]
        ON [cargoSAP].[IdEmpresaReferencia] = @IdEmpresaReferencia
       AND [cargoSAP].[CodigoCargoSAP] = [carga].[CodigoCargoSAP]
    WHERE [cargoSAP].[IdCargoSAP] IS NULL
)
    THROW 51003, N'No se encontró uno de los cargos SAP de Golden.', 1;

IF EXISTS
(
    SELECT 1
    FROM @Carga AS [carga]
    INNER JOIN @ColaboradoresCO AS [colaboradorCO]
        ON [colaboradorCO].[NumeroDocumento] = [carga].[NumeroDocumento]
    INNER JOIN [rrhh].[RelacionLaboral] AS [existente]
        ON [existente].[IdEmpresaReferencia] = @IdEmpresaReferencia
       AND [existente].[CodigoColaboradorSAP] = [carga].[CodigoColaboradorSAP]
    WHERE [existente].[IdColaboradorCorporativo] <> [colaboradorCO].[IdColaboradorCorporativo]
)
    THROW 51004, N'El código de colaborador SAP ya está asignado a otra relación laboral.', 1;

BEGIN TRY
    BEGIN TRANSACTION;

    INSERT INTO [rrhh].[RelacionLaboral]
    (
        [IdColaboradorCorporativo],
        [IdEmpresaReferencia],
        [CodigoColaboradorSAP],
        [IdCargoSAP],
        [FechaIngreso]
    )
    SELECT
        [colaboradorCO].[IdColaboradorCorporativo],
        @IdEmpresaReferencia,
        [carga].[CodigoColaboradorSAP],
        [cargoSAP].[IdCargoSAP],
        TRY_CONVERT(DATE, [carga].[FechaIngresoTexto], 103)
    FROM @Carga AS [carga]
    INNER JOIN @ColaboradoresCO AS [colaboradorCO]
        ON [colaboradorCO].[NumeroDocumento] = [carga].[NumeroDocumento]
    INNER JOIN [organizacion].[CargoSAP] AS [cargoSAP]
        ON [cargoSAP].[IdEmpresaReferencia] = @IdEmpresaReferencia
       AND [cargoSAP].[CodigoCargoSAP] = [carga].[CodigoCargoSAP]
    WHERE NOT EXISTS
    (
        SELECT 1
        FROM [rrhh].[RelacionLaboral] AS [existente]
        WHERE [existente].[IdEmpresaReferencia] = @IdEmpresaReferencia
          AND [existente].[IdColaboradorCorporativo] = [colaboradorCO].[IdColaboradorCorporativo]
    );

    COMMIT TRANSACTION;
END TRY
BEGIN CATCH
    IF XACT_STATE() <> 0 ROLLBACK TRANSACTION;
    THROW;
END CATCH;
